"""Write RESULTS_REVISED.md from the result CSVs so every number in the write-up is generated, not hand-copied.
Usage (from bw_recount/): python3.13 make_results_md.py   (run after recount.py and phase2/recount2.py)
"""
import pandas as pd

C = pd.read_csv('phase2/results2_cells.csv')
S = pd.read_csv('phase2/results2_scenarios.csv')
M = pd.read_csv('phase2/results2_mtyears.csv')
SETS = ['2010-17 (Phase 1, 2018 workbook)', '2010-16', '2017-20', '2021-24', '2010-24 pooled']


def cell(case, st, scope, tx='in', basis='net'):
    r = C[(C.case == case) & (C.set == st) & (C.scope == scope) & (C.transmission == tx) & (C.basis == basis)]
    return r.iloc[0]


def f0(x):
    return f'{x:+.0f}'


out = ['# Revised results (generated by make_results_md.py)', '',
       'All values are MtCO₂/yr at full operation, transmission included, net basis. '
       '"Central" = all factors at their best-supported central values (deterministic). '
       '"MC" = Monte Carlo median with 5–95% range (shared factors drawn once per draw). '
       'Net = fossil added minus clean avoided (positive = fossil larger). '
       'Per the statistics review, no probability is reported for US cells: the US sign is close to a one-factor call on pipeline displacement.', '',
       '## By set and era', '',
       '| Set | US central: clean / fossil (net) | US MC net [5–95] | Global central: clean / fossil (net) | Global MC net [5–95] |',
       '|---|---|---|---|---|']
for st in SETS:
    uc, um = cell('central', st, 'US'), cell('mc', st, 'US')
    gc, gm = cell('central', st, 'global'), cell('mc', st, 'global')
    out.append(f'| {st} | {uc.clean_p50:.0f} / {uc.fossil_p50:.0f} ({f0(uc.net_p50)}) | {f0(um.net_p50)} [{um.net_p05:.0f}, {um.net_p95:.0f}] '
               f'| {gc.clean_p50:.0f} / {gc.fossil_p50:.0f} ({f0(gc.net_p50)}) | {f0(gm.net_p50)} [{gm.net_p05:.0f}, {gm.net_p95:.0f}] |')
g1 = cell('mc', SETS[0], 'global')
out += ['', f'Phase 1 global/net clean-to-fossil ratio (MC): {g1.ratio_p50:.2f} [{g1.ratio_p05:.2f}–{g1.ratio_p95:.2f}], '
        f'i.e. fossil about {1 / g1.ratio_p50:.1f}x clean ({1 / g1.ratio_p95:.1f}–{1 / g1.ratio_p05:.1f}x).', '']

out += ['## Litigation-weighted (B&W rates drawn from Jeffreys Beta per subsector)', '',
        '| Set | US MC: clean / fossil, net [5–95] | Global MC: clean / fossil, net [5–95] |', '|---|---|---|']
for st in [SETS[0], '2021-24', '2010-24 pooled']:
    u, g = cell('mc_litigation_beta_rates', st, 'US'), cell('mc_litigation_beta_rates', st, 'global')
    out.append(f'| {st} | {u.clean_p50:.0f} / {u.fossil_p50:.0f}, {f0(u.net_p50)} [{u.net_p05:.0f}, {u.net_p95:.0f}] '
               f'| {g.clean_p50:.0f} / {g.fossil_p50:.0f}, {f0(g.net_p50)} [{g.net_p05:.0f}, {g.net_p95:.0f}] |')

b = cell('built_only_mc', '2021-24', 'US')
out += ['', f'2021–24 built or under construction only (US, MC): clean {b.clean_p50:.0f} vs fossil {b.fossil_p50:.0f}, '
        f'net {f0(b.net_p50)} [{b.net_p05:.0f}, {b.net_p95:.0f}].', '']

out += ['## Scenario table (central factors; net = fossil minus clean)', '']
for scope in ['US', 'global']:
    t = S[S.scope == scope].pivot_table(index='scenario', columns='set', values='net_fossil_minus_clean', sort=False)
    t = t[[s for s in SETS if s in t.columns]]
    out += [f'**{scope}, net**', '', '| Scenario | ' + ' | '.join(t.columns) + ' |', '|---' * (len(t.columns) + 1) + '|']
    for sc, row in t.iterrows():
        out.append(f'| {sc} | ' + ' | '.join('' if pd.isna(v) else f0(v) for v in row.values) + ' |')
    out.append('')

out += ['## Mt brought forward (internal only; not a valid clean-vs-fossil effect estimate)', '',
        'CGEP replays end at the federal decision, so post-approval suits, where the clean/fossil difference sits, are outside them. '
        'Depletables get 0 months. Pooled 2010–24, central:', '',
        '| Case | Transmission | US clean / fossil | Global clean / fossil |', '|---|---|---|---|']
for case in ['mt_brought_forward_central: covered_types (unmatched at type mean)',
             'mt_brought_forward_central: uncovered flow assets=pipeline median (1.5 mo)']:
    for tx in ['in', 'out']:
        r = M[(M.case == case) & (M.set == '2010-24 pooled') & (M.transmission == tx) & (M.basis == 'net')]
        u, g = r[r.scope == 'US'].iloc[0], r[r.scope == 'global'].iloc[0]
        out.append(f'| {case.split(": ", 1)[1]} | {tx} | {u.clean_p50:.1f} / {u.fossil_p50:.1f} | {g.clean_p50:.1f} / {g.fossil_p50:.1f} |')

open('RESULTS_REVISED.md', 'w').write('\n'.join(out) + '\n')
print('\n'.join(out))
